#!/usr/bin/env python3
"""Write ``i18n_united/plurals/_aliases.py``: deprecated language subtags CLDR renamed.

``cldr/plurals.json`` lists rules under current identifiers only, so a tag that CLDR has since
renamed — ``iw``, ``in``, ``ji``, and every ISO 639-2 three-letter code — matches nothing and would
answer ``other`` for every count. ``Intl.PluralRules`` does not: it canonicalizes the tag first, so
``iw`` is Hebrew there. The alias table closes that gap and is extracted from the same place the
rules are verified against — CLDR's ``languageAlias`` data as ICU carries it, reachable from Node as
``Intl.getCanonicalLocales``.

The extraction is a sweep, not a hand-written list: every two- and three-letter subtag is offered to
Node, and the ones it rewrites are kept when the rewrite lands somewhere plain widening does not.
CLDR's few multi-subtag legacy tags are offered too (``art-lojban``, ``zh-xiang``, …); Node rejects
most of them as malformed.

Three exclusions:

* A tag ``cldr/plurals.json`` itself carries keeps its vendored rules. ICU aliases ``jw`` → ``jv``,
  ``mo`` → ``ro``, ``sh`` → ``sr`` and ``tl`` → ``fil``, but CLDR still publishes cardinal rules
  under all four, and the vendored file is this project's source of truth (PROGRESS.md decision 3).
  Those four are exactly the ids the Node cross-check excludes for the same reason.
* A rewrite that changes nothing — both tags widen to the same rule set — is not worth a row.
* A rewrite onto a language CLDR has no rules for is worse than no rewrite: ``zh-xiang`` widens to
  ``zh`` and canonicalizes to ``hsn``, which is not in the data.

Needs Node on PATH. Run it with no arguments::

    python scripts/generate_plural_aliases.py
"""

import json
import string
import subprocess
import sys

from itertools import product
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT = REPO_ROOT / "i18n_united" / "plurals" / "_aliases.py"

# Run from anywhere without installing the package first.
sys.path.insert(0, str(REPO_ROOT))

from i18n_united.plurals import ROOT_LOCALE  # noqa: E402
from i18n_united.plurals._generated import RULES  # noqa: E402

#: CLDR's legacy identifiers that are more than one subtag long. Enumerating them is not possible
#: the way the letter sweep enumerates language subtags, so they are named.
LEGACY_TAGS = (
    "art-lojban",
    "cel-gaulish",
    "i-klingon",
    "no-bok",
    "no-nyn",
    "zh-guoyu",
    "zh-hakka",
    "zh-min",
    "zh-min-nan",
    "zh-xiang",
)

#: Ask Node for the canonical form of every candidate, skipping the ones it calls malformed.
_CANONICALIZE_JS = """
const out = {};
for (const tag of JSON.parse(process.argv[1])) {
  try {
    const canonical = Intl.getCanonicalLocales(tag)[0];
    if (canonical) out[tag] = canonical.toLowerCase();
  } catch { /* not a well-formed tag, so no aliasing to learn from it */ }
}
console.log(JSON.stringify(out));
"""


def candidates() -> list[str]:
    letters = string.ascii_lowercase
    two = ["".join(pair) for pair in product(letters, repeat=2)]
    three = ["".join(triple) for triple in product(letters, repeat=3)]
    return [*two, *three, *LEGACY_TAGS]


def canonicalize(tags: list[str]) -> dict[str, str]:
    """``{tag: canonical form}`` from Node, for the tags it accepts."""
    result = subprocess.run(
        ["node", "-e", _CANONICALIZE_JS, json.dumps(tags)],
        capture_output=True,
        text=True,
        check=True,
    )
    return json.loads(result.stdout)


def widen(tag: str) -> str:
    """``resolve_locale`` without the alias step — the widening the table has to improve on."""
    while tag:
        if tag in RULES:
            return tag
        tag, _, _ = tag.rpartition("-")
    return ROOT_LOCALE


def build_table(canonical: dict[str, str]) -> dict[str, str]:
    table = {}
    for tag, replacement in sorted(canonical.items()):
        if replacement == tag or tag in RULES:
            continue
        if widen(tag) == widen(replacement):
            continue
        # The replacement has to be a language CLDR has rules for. `zh-xiang` canonicalizes to
        # `hsn`, which CLDR does not carry, so following the alias would trade the `zh` that
        # widening finds for nothing at all. (Node answers such a tag from its *default* locale
        # rather than from root, which is an Intl fallback artefact and not plural data.)
        if widen(replacement) == ROOT_LOCALE:
            continue
        table[tag] = replacement
    return table


def generate(table: dict[str, str], node_version: str, icu_version: str) -> str:
    lines = [
        '"""Deprecated language subtags mapped to their current CLDR identifier.',
        "",
        "Generated by scripts/generate_plural_aliases.py from Intl.getCanonicalLocales in",
        f"Node {node_version} (ICU {icu_version}), which is CLDR's languageAlias data as ICU carries",
        "it. Do not edit by hand: re-run the generator instead.",
        "",
        "Only tags that change the answer are listed: a tag `cldr/plurals.json` carries itself keeps",
        "its vendored rules (jw, mo, sh, tl), and a rewrite that widens to the same rule set anyway",
        "earns no row. The replacement is the full canonical tag, not the rule-set key, so",
        "`resolve_locale` still widens it — `hbs` becomes `sr-latn` and widens on to `sr`.",
        '"""',
        "",
        "#: Deprecated language subtag to its canonical replacement, both lowercase.",
        "LANGUAGE_ALIASES: dict[str, str] = {",
    ]
    lines.extend(f'    "{tag}": "{replacement}",' for tag, replacement in table.items())
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def node_versions() -> tuple[str, str]:
    result = subprocess.run(
        ["node", "-e", "console.log(JSON.stringify([process.versions.node, process.versions.icu]))"],
        capture_output=True,
        text=True,
        check=True,
    )
    node, icu = json.loads(result.stdout)
    return node, icu


def main() -> None:
    table = build_table(canonicalize(candidates()))
    node_version, icu_version = node_versions()
    OUT.write_text(generate(table, node_version, icu_version), encoding="utf-8")
    print(f"wrote {OUT}: {len(table)} aliases (Node {node_version}, ICU {icu_version})")


if __name__ == "__main__":
    main()
